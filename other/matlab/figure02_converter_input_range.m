%% Electrical Figure 02
% CONVERTER INPUT-RANGE SCREENING -- published equipment limits
% WRO 2026 Future Engineers | Engineering Journal 02: Power & Sensor Architecture
%
% IMPORTANT: This is a SPECIFICATION SCREEN, not a regulator-output model.
% The plotted battery-voltage sweep is an illustrative VIEWING WINDOW; it
% is NOT a safe discharge limit, measured discharge curve or charger setting.
%
% Verified published input ranges (DFRobot):
%   DFR1202 5 V / 16 A buck: VIN = 6 to 24 V.
%   DFR1208 12 V / 12 A buck: VIN = 15 to 24 V.
% GNB 4S LiHV 1300 mAh battery: VIN,nom = 15.2 V (manufacturer label).
% Reference for the LiHV full-charge endpoint: 4 x 4.35 V = 17.4 V.
% This is a nominal chemistry reference, NOT a measured terminal voltage,
% and is NOT a charging instruction; follow the pack/charger instructions.
%
% Run entire script in base MATLAB R2020a or newer (exportgraphics).
% Results: results/02_input_range_screen.png and simulation_inputs.mat.
% No CSV and no summary.txt are produced.

clearvars; close all; clc;

%% 1. USER INPUTS -- published limits and explicit visualization choices
inputs.project = 'YBR-SUNFLOWER | WRO 2026 Future Engineers';
inputs.figureID = '02/11';
inputs.dataClass = 'Published component limits + illustrative voltage sweep';

inputs.packCells = 4;              % GNB product: 4S1P
inputs.packNominalV = 15.2;        % GNB product: 15.2 V nominal
inputs.lihvFullCellReferenceV = 4.35; % typical LiHV reference (not an operational setpoint)
inputs.packFullReferenceV = inputs.packCells * inputs.lihvFullCellReferenceV;

% DFRobot published input operating ranges; these refer to converter INPUT.
inputs.buck5MinV = 6.0;            % DFR1202 published minimum VIN
inputs.buck5MaxV = 24.0;           % DFR1202 published maximum VIN
inputs.buck12MinV = 15.0;          % DFR1208 published minimum VIN
inputs.buck12MaxV = 24.0;          % DFR1208 published maximum VIN
inputs.buck5OutputNominalV = 5.0;  % informative label only; NOT simulated
inputs.buck12OutputNominalV = 12.0;% informative label only; NOT simulated

% Deliberately arbitrary VIEWING WINDOW. NOT a battery discharge cutoff!
inputs.sweepMinV = 13.0;
inputs.sweepMaxV = inputs.packFullReferenceV;
inputs.sweepPoints = 750;

%% 2. Check input consistency and calculate numerical headroom
assert(inputs.packCells == 4 && inputs.packNominalV > 0);
assert(inputs.sweepPoints >= 100 && inputs.sweepMaxV > inputs.sweepMinV);
assert(inputs.buck5MinV < inputs.buck5MaxV);
assert(inputs.buck12MinV < inputs.buck12MaxV);
assert(inputs.packFullReferenceV > inputs.packNominalV);
assert(inputs.packNominalV >= inputs.buck12MinV, ...
    'The pack nominal voltage is unexpectedly below the DFR1208 minimum.');

vin = linspace(inputs.sweepMinV, inputs.sweepMaxV, inputs.sweepPoints);
within5V = vin >= inputs.buck5MinV & vin <= inputs.buck5MaxV;
within12V = vin >= inputs.buck12MinV & vin <= inputs.buck12MaxV;
margin5V = vin - inputs.buck5MinV;
margin12V = vin - inputs.buck12MinV;

nominalMargin5V = inputs.packNominalV - inputs.buck5MinV;
nominalMargin12V = inputs.packNominalV - inputs.buck12MinV;
fullReferenceMargin12V = inputs.packFullReferenceV - inputs.buck12MinV;

% Illustrative undervoltage comparison only, using the assumed sweep range.
% Do not interpret fractions of the voltage axis as time or battery SOC.

%% 3. Figure styling -- dark headings, clean grid, light small annotations
ink      = [0.10 0.15 0.23];
muted    = [0.33 0.39 0.47];
gridGrey = [0.85 0.88 0.92];
blue     = [0.17 0.40 0.70];
teal     = [0.10 0.51 0.46];
amber    = [0.77 0.40 0.14];
warn     = [0.72 0.27 0.24];

fig = figure('Color','w','Units','pixels', ...
    'Position',[65 65 1480 920]);
set(fig,'InvertHardcopy','off');

annotation(fig,'textbox',[0.065 0.923 0.88 0.055], ...
    'String','02  |  Converter input-range screening', ...
    'FontName','Arial','FontSize',21,'FontWeight','bold', ...
    'Color',ink,'LineStyle','none','Interpreter','none');

annotation(fig,'textbox',[0.066 0.871 0.88 0.040], ...
    'String','Manufacturer limits compared with the GNB 4S LiHV battery voltage', ...
    'FontName','Arial','FontSize',12.5,'Color',muted, ...
    'LineStyle','none','Interpreter','none');

%% 4. Upper panel: published converter input ranges
ax1 = axes('Parent',fig, ...
    'Position',[0.225 0.605 0.695 0.205], ...
    'Color',[1 1 1]);
hold(ax1,'on');

plot(ax1,[0 24],[2 2],'-', ...
    'Color',gridGrey,'LineWidth',12);
plot(ax1,[0 24],[1 1],'-', ...
    'Color',gridGrey,'LineWidth',12);

plot(ax1,[inputs.buck5MinV inputs.buck5MaxV], ...
    [2 2],'-','Color',blue,'LineWidth',12);
plot(ax1,[inputs.buck12MinV inputs.buck12MaxV], ...
    [1 1],'-','Color',teal,'LineWidth',12);

plot(ax1,inputs.buck5MinV,2,'o', ...
    'MarkerSize',9,'MarkerFaceColor','w', ...
    'MarkerEdgeColor',blue,'LineWidth',2);
plot(ax1,inputs.buck12MinV,1,'o', ...
    'MarkerSize',9,'MarkerFaceColor','w', ...
    'MarkerEdgeColor',teal,'LineWidth',2);
plot(ax1,24,1,'o',24,2,'o', ...
    'MarkerSize',7,'MarkerFaceColor','w', ...
    'MarkerEdgeColor',muted,'LineWidth',1.2);

plot(ax1,[inputs.packNominalV inputs.packNominalV], ...
    [0.52 2.47],'--','Color',amber,'LineWidth',1.5);
plot(ax1,[inputs.packFullReferenceV inputs.packFullReferenceV], ...
    [0.52 2.47],':','Color',muted,'LineWidth',1.4);

text(ax1,inputs.buck5MinV,2.22,'6 V min', ...
    'Color',blue,'FontName','Arial','FontSize',10.5, ...
    'FontWeight','bold','HorizontalAlignment','center');

text(ax1,inputs.buck12MinV,1.22,'15 V min', ...
    'Color',teal,'FontName','Arial','FontSize',10.5, ...
    'FontWeight','bold','HorizontalAlignment','center');

text(ax1,inputs.packNominalV,2.46,'15.2 V nominal', ...
    'Color',amber,'FontName','Arial','FontSize',10.4, ...
    'HorizontalAlignment','right', ...
    'VerticalAlignment','bottom');

text(ax1,inputs.packFullReferenceV,2.46, ...
    '17.4 V LiHV reference', ...
    'Color',muted,'FontName','Arial','FontSize',10.4, ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','bottom');

set(ax1,'XLim',[0 25],'YLim',[0.52 2.85], ...
    'YTick',[1 2], ...
    'YTickLabel',{'DFR1208  |  12 V output', ...
                  'DFR1202  |  5 V output'}, ...
    'XTick',0:3:24,'FontName','Arial','FontSize',11.7, ...
    'XColor',ink,'YColor',ink,'LineWidth',0.9, ...
    'TickLength',[0 0], ...
    'Box','off','XGrid','on','YGrid','off', ...
    'GridColor',gridGrey,'GridAlpha',0.75, ...
    'Layer','bottom');

ax1.Color = [1 1 1];

xlabel(ax1,'Published converter input-voltage range (V)', ...
    'Color',ink,'FontName','Arial','FontSize',12, ...
    'FontWeight','bold');

%% 5. Lower panel: DFR1208 input headroom
ax2 = axes('Parent',fig, ...
    'Position',[0.120 0.300 0.800 0.245], ...
    'Color',[1 1 1]);
hold(ax2,'on');

invalidRight = min(inputs.buck12MinV,inputs.sweepMaxV);

if invalidRight > inputs.sweepMinV
    patch(ax2, ...
        [inputs.sweepMinV invalidRight invalidRight inputs.sweepMinV], ...
        [-3 -3 3 3],[1.0 0.93 0.93], ...
        'EdgeColor','none','FaceAlpha',0.80);
end

plot(ax2,vin,margin12V,'-', ...
    'Color',teal,'LineWidth',2.7);

plot(ax2,[inputs.sweepMinV inputs.packFullReferenceV], ...
    [0 0],'--','Color',warn,'LineWidth',1.7);

plot(ax2,[inputs.packNominalV inputs.packNominalV], ...
    [-2.0 2.75],':','Color',amber,'LineWidth',1.4);

plot(ax2,inputs.packNominalV,nominalMargin12V,'o', ...
    'MarkerSize',10,'MarkerFaceColor',amber, ...
    'MarkerEdgeColor','w','LineWidth',1.6);

plot(ax2,inputs.packFullReferenceV,fullReferenceMargin12V,'o', ...
    'MarkerSize',9,'MarkerFaceColor',teal, ...
    'MarkerEdgeColor','w','LineWidth',1.5);

text(ax2,13.15,-1.75, ...
    'Below stated 15 V input minimum', ...
    'Color',warn,'FontSize',10.3,'FontName','Arial');

text(ax2,15.43,0.66, ...
    sprintf('Nominal margin: +%.2f V',nominalMargin12V), ...
    'Color',ink,'FontName','Arial','FontSize',11.2, ...
    'FontWeight','bold');

text(ax2,17.27,2.68, ...
    sprintf('LiHV reference: +%.1f V',fullReferenceMargin12V), ...
    'Color',muted,'FontName','Arial','FontSize',10.1, ...
    'HorizontalAlignment','right');

set(ax2,'XLim',[13 17.75],'YLim',[-2.12 2.92], ...
    'XTick',[13 14 15 15.2 16 17 17.4], ...
    'XTickLabel',{'13','14','15','15.2','16','17','17.4'}, ...
    'YTick',-2:1:2,'FontName','Arial','FontSize',11, ...
    'XColor',ink,'YColor',ink,'LineWidth',0.95, ...
    'TickLength',[0 0], ...
    'Box','off','XGrid','on','YGrid','on', ...
    'GridColor',gridGrey,'GridAlpha',0.68, ...
    'Layer','top');

ax2.Color = [1 1 1];

xlabel(ax2,'Illustrative battery terminal voltage (V)', ...
    'Color',ink,'FontName','Arial','FontSize',12, ...
    'FontWeight','bold');

ylabel(ax2,'DFR1208 margin vs. 15 V (V)', ...
    'Color',ink,'FontName','Arial','FontSize',11.3, ...
    'FontWeight','bold');

%% 6. Footer -- separated from the graph
annotation(fig,'textbox',[0.066 0.155 0.89 0.055], ...
    'String',sprintf( ...
    ['Published VIN: DFR1202 6-24 V  |  DFR1208 15-24 V.  ', ...
     'At 15.2 V nominal: +%.1f V / +%.1f V above each converter''s minimum.'], ...
    nominalMargin5V,nominalMargin12V), ...
    'FontName','Arial','FontSize',11, ...
    'FontWeight','bold','Color',ink, ...
    'LineStyle','none','Interpreter','none');

%% 7. Save PNG and model inputs; no CSV or text-summary files
scriptDir=fileparts(mfilename('fullpath'));
if isempty(scriptDir), scriptDir=pwd; end
outDir=fullfile(scriptDir,'results');
if ~exist(outDir,'dir'), mkdir(outDir); end
figurePath=fullfile(outDir,'02_input_range_screen.png');
exportgraphics(fig,figurePath,'Resolution',240,'BackgroundColor','white');
save(fullfile(outDir,'simulation_inputs.mat'), ...
    'inputs','vin','within5V','within12V','margin5V','margin12V', ...
    'nominalMargin5V','nominalMargin12V','fullReferenceMargin12V');

fprintf('\nYBR-SUNFLOWER | ELECTRICAL FIGURE 02/11\n');
fprintf('DFR1202 published input: %.1f to %.1f V (5 V nominal output)\n', ...
    inputs.buck5MinV,inputs.buck5MaxV);
fprintf('DFR1208 published input: %.1f to %.1f V (12 V nominal output)\n', ...
    inputs.buck12MinV,inputs.buck12MaxV);
fprintf('GNB LiHV battery nominal: %.2f V; reference full %.2f V\n', ...
    inputs.packNominalV,inputs.packFullReferenceV);
fprintf('Nominal input headroom: DFR1202 %.2f V, DFR1208 %.2f V\n', ...
    nominalMargin5V,nominalMargin12V);
fprintf('DFR1208 nominal voltage margin is only %.2f V.\n', ...
    nominalMargin12V);
fprintf('Saved one figure: %s\n',figurePath);
fprintf('CAUTION: This screen cannot predict dropout voltage, runtime, or safe discharge cutoff.\n\n');
